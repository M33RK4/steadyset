/**
 * Generates the SQL migration that seeds the built-in exercise library from
 * src/lib/data/exercises.ts, so ids in the database always match the ids in the app.
 * Run with: npm run db:generate-library
 */
import { writeFileSync } from "node:fs";
import { BUILT_IN_EXERCISES } from "../src/lib/data/exercises";

const q = (s: string | undefined | null) => (s === undefined || s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

const rows = BUILT_IN_EXERCISES.map(
  (e) =>
    `  (${q(e.id)}, null, ${q(e.slug)}, ${q(e.name)}, ${q(e.kind)}, ${arr(e.primaryMuscles)}, ${arr(e.secondaryMuscles)}, ${arr(e.equipment)}, ${q(e.difficulty)}, ${e.usesWeight}, ${q(e.startingPosition)}, ${arr(e.steps)}, ${q(e.breathing)}, ${arr(e.mistakes)}, ${arr(e.safety)}, ${q(e.animation)})`,
);

const sql = `-- GENERATED by scripts/generate-exercise-migration.ts — do not edit by hand.
-- Built-in exercise library (owner_id null). Safe to re-run.
insert into public.exercises
  (id, owner_id, slug, name, kind, primary_muscles, secondary_muscles, equipment, difficulty, uses_weight, starting_position, steps, breathing, mistakes, safety, animation)
values
${rows.join(",\n")}
on conflict (id) do update set
  slug = excluded.slug, name = excluded.name, kind = excluded.kind,
  primary_muscles = excluded.primary_muscles, secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment, difficulty = excluded.difficulty, uses_weight = excluded.uses_weight,
  starting_position = excluded.starting_position, steps = excluded.steps, breathing = excluded.breathing,
  mistakes = excluded.mistakes, safety = excluded.safety, animation = excluded.animation;
`;

const out = process.argv[2] ?? "supabase/migrations/20261027000003_exercise_library.sql";
writeFileSync(out, sql);
console.log(`Wrote ${BUILT_IN_EXERCISES.length} exercises to ${out}`);
