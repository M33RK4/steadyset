export const BUILT_IN_EXERCISES: Exercise[] = defs.map((d) => ({
  ...d,
  id: stableId(EXERCISE_NAMESPACE, d.slug),
  ownerId: null,
  animation: d.animation ?? d.slug,
}));

export const exerciseIdBySlug = (slug: string): string => {
  const ex = BUILT_IN_EXERCISES.find((e) => e.slug === slug);
  if (!ex) throw new Error(`Unknown exercise slug: ${slug}`);
  return ex.id;
};

export const MUSCLE_FILTERS = ["Glutes", "Legs", "Chest", "Back", "Shoulders", "Arms", "Core", "Cardio", "Mobility"] as const;

/** Floor drills and stretches for the hips, listed under Mobility as well as their muscles. */
const HIP_MOBILITY = new Set(["adductor-rock-back","lunge-rock","seated-straight-leg-raise","side-lunge-rock","ninety-ninety-foot-lift","ninety-ninety-knee-lift","pigeon-backbend","supine-knee-drop","side-sit-leg-lift","low-lunge-quad-stretch","kneel-to-squat","couch-stretch","ninety-ninety-switch"]);

/** Rough grouping used by the library filter chips. */
export function muscleGroupOf(ex: Exercise): string[] {
  const all = [...ex.primaryMuscles, ...ex.secondaryMuscles].join(" ").toLowerCase();
  const groups: string[] = [];
  if (all.includes("glute")) groups.push("Glutes");
  if (/quad|hamstring|adductor|legs|hip stab|calves/.test(all)) groups.push("Legs");
  if (all.includes("chest")) groups.push("Chest");
  if (/back|lats/.test(all)) groups.push("Back");
  if (/shoulder|traps/.test(all)) groups.push("Shoulders");
  if (/biceps|triceps|forearm|brachialis/.test(all)) groups.push("Arms");
  if (all.includes("core")) groups.push("Core");
  if (ex.kind === "cardio") groups.push("Cardio");
  if (ex.kind === "mobility" || HIP_MOBILITY.has(ex.slug)) groups.push("Mobility");
  return groups;
}
